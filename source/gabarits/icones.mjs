/* Pictogramme : nom direct, ou code météo (de nuit, soleil → lune). */
export function icone(nom, classe = 'ico') {
  return brut(`<svg class="${classe}" aria-hidden="true" focusable="false"><use href="#i-${nom}"/></svg>`);
}

export function iconeCode(codes, code, jour = 1) {
  const e = codes[String(code)] || codes['3'];
  let n = e[1];
  if (!jour && n === 'soleil') n = 'lune';
  if (!jour && n === 'eclaircies') n = 'eclaircies-nuit';
  return n;
}
